def _config_bool(clave, por_defecto=True):
    """read_config convierte todo a string, asi que "0"/"false" llegan como texto."""

    valor = app_config.get(clave)
    if valor is None:
        return por_defecto

    return str(valor).strip().lower() not in ("0", "false", "no", "")


